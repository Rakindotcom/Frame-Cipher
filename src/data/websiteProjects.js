/**
 * Returns projects tailored specifically to a website service category.
 *
 * @param {string} category - Service sub-slug or category identifier.
 * @param {number} limit - Maximum number of showcase projects (default: 3).
 * @returns {Array} List of matching projects.
 */
export function getWebsitesByCategory(category = '', limit = 4) {
  if (!category || category === 'pillar' || category === 'all') {
    return [
      websiteProjects.find((p) => p.name === 'Jarixo'),
      websiteProjects.find((p) => p.name === 'Dont Validate Labels'),
      websiteProjects.find((p) => p.name === 'Dr. Ferdoush Saleheen'),
    ].filter(Boolean).slice(0, limit)
  }

  const clean = category.toLowerCase().trim()

  if (clean === 'shopify') {
    return websiteProjects
      .filter((p) => p.platform === 'Shopify' || p.tags?.includes('shopify'))
      .slice(0, limit)
  }

  if (clean === 'wordpress') {
    return websiteProjects
      .filter((p) => p.platform === 'WordPress')
      .slice(0, limit)
  }

  if (clean === 'ecommerce-website' || clean === 'ecommerce') {
    return websiteProjects
      .filter((p) => p.tags?.includes('ecommerce-website'))
      .slice(0, limit)
  }

  if (clean === 'business-website' || clean === 'business') {
    return websiteProjects
      .filter((p) => p.tags?.includes('business-website'))
      .slice(0, limit)
  }

  if (clean === 'custom-development' || clean === 'custom') {
    return websiteProjects
      .filter((p) => p.tags?.includes('custom-development'))
      .slice(0, limit)
  }

  if (clean === 'landing-pages' || clean === 'landing') {
    return websiteProjects
      .filter((p) => p.tags?.includes('landing-pages'))
      .slice(0, limit)
  }

  if (clean === 'ui-ux-design' || clean === 'ui-ux') {
    return websiteProjects
      .filter((p) => p.tags?.includes('ui-ux-design'))
      .slice(0, limit)
  }

  if (clean === 'redesign') {
    return websiteProjects
      .filter((p) => p.tags?.includes('redesign'))
      .slice(0, limit)
  }

  if (clean === 'wix') {
    return websiteProjects
      .filter((p) => p.tags?.includes('wix'))
      .slice(0, limit)
  }

  if (clean === 'magento') {
    return websiteProjects
      .filter((p) => p.tags?.includes('magento'))
      .slice(0, limit)
  }

  if (clean === 'maintenance') {
    return websiteProjects
      .filter((p) => p.tags?.includes('maintenance'))
      .slice(0, limit)
  }

  if (clean === 'webflow') {
    return websiteProjects
      .filter((p) => p.tags?.includes('webflow'))
      .slice(0, limit)
  }

  // Master pillar default showcase: diverse platform mix
  return [
    websiteProjects.find((p) => p.name === 'Jarixo'),
    websiteProjects.find((p) => p.name === 'Dont Validate Labels'),
    websiteProjects.find((p) => p.name === 'Dr. Ferdoush Saleheen'),
  ].filter(Boolean).slice(0, limit)
}
