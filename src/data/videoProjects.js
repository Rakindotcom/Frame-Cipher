export const allVideos = [...longVideos, ...shortVideos]

/**
 * Filter videos by category/genre/tags.
 *
 * @param {string} category - e.g. 'product-promotion', 'podcast', 'commercial', 'short', 'long'
 * @param {number} limit - maximum items to return
 */
export function getVideosByCategory(category = '', limit = 6) {
  if (!category || category === 'all') {
    return allVideos.slice(0, limit)
  }

  const clean = category.toLowerCase().trim()

  if (clean === 'product-promotion' || clean === 'product-promo' || clean === 'ecommerce') {
    return shortVideos.filter((v) => v.genre === 'product-promotion' || v.tags?.includes('product-promotion')).slice(0, limit)
  }

  if (clean === 'podcast' || clean === 'podcasts' || clean === 'interview') {
    const shorts = shortVideos.filter((v) => v.genre === 'podcast')
    const longs = longVideos.filter((v) => v.genre === 'podcast')
    return [...shorts, ...longs].slice(0, limit)
  }

  if (clean === 'commercial' || clean === 'commercial-video' || clean === 'promotional') {
    return shortVideos.filter((v) => v.tags?.includes('commercial') || v.genre === 'product-promotion').slice(0, limit)
  }

  if (clean === 'corporate' || clean === 'corporate-video' || clean === 'company-profile') {
    // Corporate work is long-form (16:9). Keep vertical shorts out of this
    // showcase so the row stays visually consistent.
    return longVideos
      .filter((v) => v.tags?.includes('corporate') || v.genre === 'corporate')
      .slice(0, limit)
  }

  if (clean === 'short' || clean === 'short-form') {
    return shortVideos.slice(0, limit)
  }

  if (clean === 'long' || clean === 'long-form') {
    return longVideos.slice(0, limit)
  }

  return allVideos.filter((v) => v.tags?.includes(clean) || v.genre === clean).slice(0, limit)
}
